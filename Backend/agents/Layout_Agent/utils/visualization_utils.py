# =============================================================================
# TOPOLOGY DEBUG COLOR
# =============================================================================

def topology_debug_color(

    score: float
):

    if score >= 90:

        return "#1B5E20"

    elif score >= 75:

        return "#4CAF50"

    elif score >= 60:

        return "#FBC02D"

    elif score >= 45:

        return "#FB8C00"

    return "#C62828"