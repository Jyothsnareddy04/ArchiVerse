# =============================================================================
# TOPOLOGY SCORE COLOR
# =============================================================================


def score_color(

    score: float
):

    if score >= 85:

        return "#4CAF50"

    if score >= 70:

        return "#8BC34A"

    if score >= 55:

        return "#FFC107"

    if score >= 40:

        return "#FF9800"

    return "#F44336"

