# =============================================================================
# TEXT COLOR
# =============================================================================


def text_color(

    room_type: str
):

    dark_rooms = [

        "kitchen",

        "bathroom",

        "staircase"
    ]

    if room_type in dark_rooms:

        return "#FFFFFF"

    return "#212121"

