# =============================================================================
# ROOM ALPHA
# =============================================================================


def room_alpha(

    room_type: str
):

    if room_type in [

        "lawn",

        "backyard",

        "green_strip"
    ]:

        return 0.45

    if room_type in [

        "parking",

        "wash_area"
    ]:

        return 0.65

    return 0.72

